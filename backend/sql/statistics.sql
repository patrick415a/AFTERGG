-- 챔피언 통계: 경기/참가자 기본키 덕분에 여러 사람이 같은 경기를 갱신해도 중복 집계되지 않습니다.
-- legacy는 패치·다른 참가자 PUUID가 없으므로 정확한 집계에서 제외합니다.
SELECT m.PATCH_VERSION, m.QUEUE_ID, p.POSITION_NAME, p.CHAMPION_ID,
       COUNT(*) AS GAMES, SUM(p.WIN) AS WINS,
       ROUND(100 * SUM(p.WIN) / COUNT(*), 2) AS WIN_RATE
FROM LOL_MATCHES m
JOIN LOL_MATCH_PARTICIPANTS p ON p.MATCH_ID = m.MATCH_ID
WHERE m.DETAIL_COMPLETE = 1 AND m.REMAKE = 0 AND m.MAP_ID = 11 AND m.QUEUE_ID IN (420, 440)
GROUP BY m.PATCH_VERSION, m.QUEUE_ID, p.POSITION_NAME, p.CHAMPION_ID;

-- 최종 보유 아이템 통계: 같은 아이템을 두 칸에 넣어도 한 참가자는 한 번만 집계합니다.
-- 장신구(slot 6)·역할 보상(slot 7)은 제외합니다. 구매 시점/순서는 Match Timeline 수집이 별도로 필요합니다.
SELECT m.PATCH_VERSION, m.QUEUE_ID, p.CHAMPION_ID, i.ITEM_ID,
       COUNT(*) AS GAMES_WITH_ITEM, SUM(p.WIN) AS WINS,
       ROUND(100 * SUM(p.WIN) / COUNT(*), 2) AS WIN_RATE
FROM LOL_MATCHES m
JOIN LOL_MATCH_PARTICIPANTS p ON p.MATCH_ID = m.MATCH_ID
JOIN (
  SELECT DISTINCT MATCH_ID, PARTICIPANT_ID, ITEM_ID
  FROM LOL_PARTICIPANT_ITEMS WHERE SLOT_NO BETWEEN 0 AND 5 AND ITEM_ID > 0
) i ON i.MATCH_ID = p.MATCH_ID AND i.PARTICIPANT_ID = p.PARTICIPANT_ID
WHERE m.DETAIL_COMPLETE = 1 AND m.REMAKE = 0 AND m.MAP_ID = 11 AND m.QUEUE_ID IN (420, 440)
GROUP BY m.PATCH_VERSION, m.QUEUE_ID, p.CHAMPION_ID, i.ITEM_ID;
