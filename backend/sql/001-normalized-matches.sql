-- 기존 SUMMONERS / SUMMONER_MATCH_CACHE는 보존합니다.
-- npm run db:migrate가 문장별로 실행하고 이미 생성된 테이블/인덱스는 확인 후 건너뜁니다.
CREATE TABLE AFTERGG_MIGRATIONS (
  VERSION VARCHAR2(50) PRIMARY KEY,
  APPLIED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE SUMMONER_RANKS (
  PUUID VARCHAR2(100) NOT NULL REFERENCES SUMMONERS(PUUID),
  QUEUE_TYPE VARCHAR2(40) NOT NULL,
  TIER VARCHAR2(30),
  RANK_DIVISION VARCHAR2(10),
  LEAGUE_POINTS NUMBER DEFAULT 0 NOT NULL,
  WINS NUMBER DEFAULT 0 NOT NULL,
  LOSSES NUMBER DEFAULT 0 NOT NULL,
  CONSTRAINT PK_SUMMONER_RANKS PRIMARY KEY (PUUID, QUEUE_TYPE)
);

CREATE TABLE SUMMONER_SYNC (
  PUUID VARCHAR2(100) PRIMARY KEY REFERENCES SUMMONERS(PUUID),
  PROFILE_UPDATED_AT TIMESTAMP,
  LAST_REFRESH_AT TIMESTAMP,
  REFRESH_ANCHOR NUMBER,
  HISTORY_COMPLETE NUMBER(1) DEFAULT 0 NOT NULL CHECK (HISTORY_COMPLETE IN (0, 1)),
  PROFILE_WARNINGS NVARCHAR2(1000)
);

CREATE TABLE LOL_MATCHES (
  MATCH_ID VARCHAR2(64) PRIMARY KEY,
  QUEUE_ID NUMBER NOT NULL,
  GAME_VERSION VARCHAR2(40) NOT NULL,
  PATCH_VERSION VARCHAR2(20) NOT NULL,
  MAP_ID NUMBER NOT NULL,
  STARTED_AT NUMBER NOT NULL,
  PLAYED_AT NUMBER NOT NULL,
  DURATION_SECONDS NUMBER NOT NULL,
  REMAKE NUMBER(1) NOT NULL CHECK (REMAKE IN (0, 1)),
  DETAIL_COMPLETE NUMBER(1) NOT NULL CHECK (DETAIL_COMPLETE IN (0, 1)),
  STORED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE LOL_MATCH_PARTICIPANTS (
  MATCH_ID VARCHAR2(64) NOT NULL REFERENCES LOL_MATCHES(MATCH_ID),
  PARTICIPANT_ID NUMBER NOT NULL,
  PUUID VARCHAR2(100),
  GAME_NAME NVARCHAR2(100) NOT NULL,
  TAG_LINE NVARCHAR2(20),
  CHAMPION_ID NUMBER NOT NULL,
  CHAMPION_NAME VARCHAR2(60) NOT NULL,
  CHAMPION_LEVEL NUMBER NOT NULL,
  TEAM_ID NUMBER NOT NULL,
  WIN NUMBER(1) NOT NULL CHECK (WIN IN (0, 1)),
  KILLS NUMBER NOT NULL,
  DEATHS NUMBER NOT NULL,
  ASSISTS NUMBER NOT NULL,
  CS NUMBER NOT NULL,
  DAMAGE NUMBER NOT NULL,
  TAKEN NUMBER NOT NULL,
  GOLD NUMBER NOT NULL,
  KILL_PARTICIPATION NUMBER NOT NULL,
  POSITION_NAME VARCHAR2(20) NOT NULL,
  SPELL1_ID NUMBER NOT NULL,
  SPELL2_ID NUMBER NOT NULL,
  KEYSTONE_ID NUMBER NOT NULL,
  SECONDARY_RUNE_ID NUMBER NOT NULL,
  ROLE_ITEM_ID NUMBER NOT NULL,
  CONSTRAINT PK_LOL_PARTICIPANTS PRIMARY KEY (MATCH_ID, PARTICIPANT_ID)
);

CREATE TABLE LOL_PARTICIPANT_ITEMS (
  MATCH_ID VARCHAR2(64) NOT NULL,
  PARTICIPANT_ID NUMBER NOT NULL,
  SLOT_NO NUMBER NOT NULL CHECK (SLOT_NO BETWEEN 0 AND 7),
  ITEM_ID NUMBER NOT NULL,
  CONSTRAINT PK_LOL_PARTICIPANT_ITEMS PRIMARY KEY (MATCH_ID, PARTICIPANT_ID, SLOT_NO),
  CONSTRAINT FK_LOL_ITEMS_PARTICIPANT FOREIGN KEY (MATCH_ID, PARTICIPANT_ID)
    REFERENCES LOL_MATCH_PARTICIPANTS(MATCH_ID, PARTICIPANT_ID) ON DELETE CASCADE
);

-- PUUID가 없는 예전 참가자는 여러 행을 허용하고, 알려진 PUUID만 경기 내 중복을 막습니다.
CREATE UNIQUE INDEX UQ_LOL_MATCH_PLAYER ON LOL_MATCH_PARTICIPANTS (
  CASE WHEN PUUID IS NOT NULL THEN MATCH_ID END, PUUID
);
CREATE INDEX IX_LOL_PLAYER_MATCH ON LOL_MATCH_PARTICIPANTS(PUUID, MATCH_ID);
CREATE INDEX IX_LOL_CHAMPION_MATCH ON LOL_MATCH_PARTICIPANTS(CHAMPION_ID, MATCH_ID);
CREATE INDEX IX_LOL_MATCH_TIME ON LOL_MATCHES(STARTED_AT, QUEUE_ID);
CREATE INDEX IX_LOL_ITEM_MATCH ON LOL_PARTICIPANT_ITEMS(ITEM_ID, MATCH_ID);
