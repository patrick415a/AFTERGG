-- DB_USER와 같은 소환사 테이블 소유 계정으로 실행합니다. 조회만 수행합니다.
SELECT SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA,
       SESSIONTIMEZONE AS SESSION_TIME_ZONE FROM DUAL;

SELECT TABLE_NAME FROM USER_TABLES
WHERE TABLE_NAME IN ('SUMMONERS', 'SUMMONER_MATCH_CACHE', 'SUMMONER_RANKS', 'SUMMONER_SYNC',
                     'LOL_MATCHES', 'LOL_MATCH_PARTICIPANTS', 'LOL_PARTICIPANT_ITEMS', 'AFTERGG_MIGRATIONS')
ORDER BY TABLE_NAME;

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, CHAR_LENGTH, NULLABLE, IDENTITY_COLUMN
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('SUMMONERS', 'SUMMONER_MATCH_CACHE', 'SUMMONER_RANKS', 'SUMMONER_SYNC',
                     'LOL_MATCHES', 'LOL_MATCH_PARTICIPANTS', 'LOL_PARTICIPANT_ITEMS', 'AFTERGG_MIGRATIONS')
ORDER BY TABLE_NAME, COLUMN_ID;

SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('SUMMONERS', 'SUMMONER_MATCH_CACHE', 'SUMMONER_RANKS', 'SUMMONER_SYNC',
                     'LOL_MATCHES', 'LOL_MATCH_PARTICIPANTS', 'LOL_PARTICIPANT_ITEMS', 'AFTERGG_MIGRATIONS')
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;

SELECT TABLE_NAME, INDEX_NAME, UNIQUENESS, STATUS FROM USER_INDEXES
WHERE INDEX_NAME IN ('UQ_LOL_MATCH_PLAYER', 'IX_LOL_PLAYER_MATCH', 'IX_LOL_CHAMPION_MATCH',
                     'IX_LOL_MATCH_TIME', 'IX_LOL_ITEM_MATCH')
ORDER BY INDEX_NAME;

SELECT 'SUMMONERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM SUMMONERS
UNION ALL SELECT 'SUMMONER_MATCH_CACHE', COUNT(*) FROM SUMMONER_MATCH_CACHE
UNION ALL SELECT 'SUMMONER_RANKS', COUNT(*) FROM SUMMONER_RANKS
UNION ALL SELECT 'SUMMONER_SYNC', COUNT(*) FROM SUMMONER_SYNC
UNION ALL SELECT 'LOL_MATCHES', COUNT(*) FROM LOL_MATCHES
UNION ALL SELECT 'LOL_MATCH_PARTICIPANTS', COUNT(*) FROM LOL_MATCH_PARTICIPANTS
UNION ALL SELECT 'LOL_PARTICIPANT_ITEMS', COUNT(*) FROM LOL_PARTICIPANT_ITEMS
UNION ALL SELECT 'AFTERGG_MIGRATIONS', COUNT(*) FROM AFTERGG_MIGRATIONS;

SELECT VERSION, APPLIED_AT FROM AFTERGG_MIGRATIONS ORDER BY APPLIED_AT;

-- 결과가 0행이어야 합니다: 같은 경기의 알려진 PUUID 중복
SELECT MATCH_ID, PUUID, COUNT(*) AS DUPLICATE_COUNT FROM LOL_MATCH_PARTICIPANTS
WHERE PUUID IS NOT NULL GROUP BY MATCH_ID, PUUID HAVING COUNT(*) > 1;
