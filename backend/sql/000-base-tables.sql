-- 빈 DB에서 필요한 기본 테이블입니다. 기존 테이블은 db:migrate가 확인 후 유지합니다.
CREATE TABLE SUMMONERS (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PUUID VARCHAR2(100) NOT NULL CONSTRAINT UQ_SUMMONERS_PUUID UNIQUE,
  GAME_NAME NVARCHAR2(100) NOT NULL,
  TAG_LINE NVARCHAR2(20) NOT NULL,
  PROFILE_ICON_ID NUMBER,
  SUMMONER_LEVEL NUMBER,
  TIER VARCHAR2(30),
  RANK_DIVISION VARCHAR2(10),
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE SUMMONER_MATCH_CACHE (
  PUUID VARCHAR2(100) PRIMARY KEY,
  MATCH_DATA CLOB NOT NULL,
  UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT MATCH_DATA_IS_JSON CHECK (MATCH_DATA IS JSON)
);
